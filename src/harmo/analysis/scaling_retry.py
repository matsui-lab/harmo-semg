def update_scale_setup_model_file(scale_setup_path: str, model_file_path: str) -> bool:
    """Update GenericModelMaker/model_file in ScaleTool setup XML.

    Returns True when updated successfully.
    """
    if not scale_setup_path or not os.path.exists(scale_setup_path):
        return False
    if not model_file_path:
        return False

    try:
        tree = ET.parse(scale_setup_path)
        root = tree.getroot()
        elem = root.find(".//ScaleTool/GenericModelMaker/model_file")
        if elem is None:
            return False
        elem.text = model_file_path
        tree.write(scale_setup_path, encoding="UTF-8", xml_declaration=True)
        return True
    except Exception:
        return False


def _read_marker_error_max(sto_path: str) -> Optional[float]:
    """Read max(marker_error_max) from an OpenSim STO file."""
    if not sto_path or not os.path.exists(sto_path):
        return None

    try:
        header_rows = 0
        with open(sto_path, "r", encoding="utf-8", errors="ignore") as f:
            for i, line in enumerate(f):
                if "endheader" in line:
                    header_rows = i + 1
                    break

        df = pd.read_csv(sto_path, sep="\t", skiprows=header_rows)
        if "marker_error_max" not in df.columns:
            return None
        return float(df["marker_error_max"].max())
    except Exception:
        return None


def _resolve_scale_marker_error_file(scale_motion_path: str) -> Optional[str]:
    """Resolve ScaleTool marker error STO path derived from output_motion_file."""
    if not scale_motion_path:
        return None

    base, _ = os.path.splitext(scale_motion_path)
    preferred = base + "_marker_errors.sto"
    if os.path.exists(preferred):
        return preferred

    # Fallback: search sibling files generated by MarkerPlacer/IK.
    parent = os.path.dirname(scale_motion_path) or "."
    candidates = [
        os.path.join(parent, f)
        for f in os.listdir(parent)
        if f.endswith("_marker_errors.sto")
    ]
    return candidates[0] if candidates else None


def _read_scale_result_xml_max_error(xml_path: str) -> Optional[float]:
    """Read max marker error from scale_result.xml-like content."""
    if not xml_path or not os.path.exists(xml_path):
        return None

    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        # Pattern A: <MarkerPlacerResult><marker error="..."/></MarkerPlacerResult>
        marker_errors = []
        for marker in root.findall(".//MarkerPlacerResult/marker"):
            err = marker.get("error")
            if err is None:
                continue
            val = _parse_first_float(str(err))
            if val is not None:
                marker_errors.append(val)
        if marker_errors:
            return float(max(marker_errors))

        # Pattern B: <MarkerPlacerResult><max_error>...</max_error></MarkerPlacerResult>
        max_error_elem = root.find(".//MarkerPlacerResult/max_error")
        if max_error_elem is not None and max_error_elem.text:
            val = _parse_first_float(max_error_elem.text)
            if val is not None:
                return float(val)
    except Exception:
        return None

    return None


def _read_max_error_from_opensim_log(log_path: str) -> Optional[float]:
    """Read latest MarkerPlacer max error from OpenSim log tail."""
    if not log_path or not os.path.exists(log_path):
        return None

    # ScaleTool marker placement logs are usually like:
    # Frame at (t = 0.0): ... marker error: RMS = ..., max = 0.106 (LSK1)
    pattern = re.compile(r"Frame at \(t\s*=\s*[^\)]*\):.*?max\s*=\s*([-+]?\d*\.?\d+(?:[eE][-+]?\d+)?)")

    try:
        with open(log_path, "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            # Read only tail region to avoid scanning very large log files.
            read_size = min(size, 2 * 1024 * 1024)
            f.seek(-read_size, os.SEEK_END)
            tail = f.read().decode("utf-8", errors="ignore")

        matches = pattern.findall(tail)
        if not matches:
            return None
        return float(matches[-1])
    except Exception:
        return None


def extract_scale_max_error(scale_setup_path: str) -> Optional[float]:
    """Extract scaling max error from MarkerPlacer error STO.

    Uses the same strategy as validation.json IK metrics:
    read ``*_marker_errors.sto`` and take ``max(marker_error_max)``.
    """
    # Backward-compatibility path: sometimes callers pass scale_result.xml directly.
    xml_max = _read_scale_result_xml_max_error(scale_setup_path)
    if xml_max is not None:
        return xml_max

    scale_motion_path = resolve_scale_motion_path(scale_setup_path)
    if scale_motion_path:
        error_file = _resolve_scale_marker_error_file(scale_motion_path)
        if error_file:
            sto_max = _read_marker_error_max(error_file)
            if sto_max is not None:
                return sto_max

        # Fallback to OpenSim log near the setup directory and current cwd.
        setup_dir = os.path.dirname(scale_setup_path) or "."
        for candidate in (
            os.path.join(setup_dir, "opensim.log"),
            os.path.join(os.getcwd(), "opensim.log"),
        ):
            log_max = _read_max_error_from_opensim_log(candidate)
            if log_max is not None:
                return log_max

    # Final fallback: if setup has output_scale_file, try parse scale_result.xml.
    scale_result_path = resolve_scale_result_path(scale_setup_path)
    if scale_result_path:
        xml_max = _read_scale_result_xml_max_error(scale_result_path)
        if xml_max is not None:
            return xml_max

    return None
