from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET
from typing import Any, Dict, Optional

import pandas as pd

_ALLOWED_MODES = {
    "once",
    "until_max_error_or_max_iterations",
}


_FLOAT_RE = re.compile(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?")


def _parse_first_float(value: str) -> Optional[float]:
    match = _FLOAT_RE.search(value)
    if not match:
        return None
    try:
        return float(match.group(0))
    except ValueError:
        return None


def resolve_scaling_iteration_config(scaling_cfg: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize scaling iteration policy with safe defaults."""
    raw = scaling_cfg.get("iteration_control", {}) if isinstance(scaling_cfg, dict) else {}

    mode = str(raw.get("mode", "once"))
    if mode not in _ALLOWED_MODES:
        mode = "once"

    try:
        max_error_threshold = float(raw.get("max_error_threshold", 0.04))
        if max_error_threshold < 0:
            max_error_threshold = 0.04
    except (TypeError, ValueError):
        max_error_threshold = 0.04

    try:
        max_iterations = int(raw.get("max_iterations", 20))
        if max_iterations < 1:
            max_iterations = 1
    except (TypeError, ValueError):
        max_iterations = 20

    return {
        "mode": mode,
        "max_error_threshold": max_error_threshold,
        "max_iterations": max_iterations,
    }


def resolve_scale_result_path(scale_setup_path: str) -> Optional[str]:
    """Resolve output_scale_file path from ScaleTool setup XML."""
    if not os.path.exists(scale_setup_path):
        return None

    try:
        tree = ET.parse(scale_setup_path)
        root = tree.getroot()
        elem = root.find(".//ScaleTool/ModelScaler/output_scale_file")
        if elem is None or not elem.text:
            return None
        path = elem.text.strip()
        if not path:
            return None
        if os.path.isabs(path):
            return path
        return os.path.join(os.path.dirname(scale_setup_path), path)
    except Exception:
        return None


