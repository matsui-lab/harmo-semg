"""Posit Workbench (RStudio Server) integration helpers.

When harmo is used within Posit Workbench, the R scripts in
``harmo.r_bridge.scripts`` can be opened directly in the RStudio IDE
for interactive analysis.  This module provides utilities to make
that workflow seamless.
"""
from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)

SCRIPTS_DIR = Path(__file__).parent / "scripts"


def detect_posit_workbench() -> bool:
    """Return ``True`` if running inside Posit Workbench / RStudio Server."""
    indicators = (
        "RSTUDIO",
        "RSTUDIO_SESSION_PORT",
        "RS_SERVER_URL",
        "RSTUDIO_HTTP_REFERER",
    )
    return any(os.environ.get(var) for var in indicators)


def get_warehouse_path(config_path: Optional[str] = None) -> str:
    """Resolve the Iceberg warehouse path.

    Priority:
      1. ``HARMO_WAREHOUSE_PATH`` environment variable
      2. ``warehouse_path`` from config.yaml (if *config_path* given)
      3. ``<workspace>/warehouse/warehouse`` fallback
    """
    env_path = os.environ.get("HARMO_WAREHOUSE_PATH")
    if env_path and Path(env_path).is_dir():
        return env_path

    if config_path:
        try:
            from harmo.config.loader import load_config
            cfg = load_config(config_path)
            wp = cfg.get("warehouse_path")
            if wp and Path(wp).is_dir():
                return str(wp)
        except Exception:
            pass

    # Fallback: look relative to the workspace root
    candidates = [
        Path.cwd() / "warehouse" / "warehouse",
        Path(__file__).resolve().parents[3] / "warehouse" / "warehouse",
    ]
    for c in candidates:
        if c.is_dir():
            return str(c)

    return str(Path.cwd() / "warehouse" / "warehouse")


def create_r_project_link(target_dir: Optional[str] = None) -> Path:
    """Create a symlink to the R scripts directory for easy RStudio access.

    Parameters
    ----------
    target_dir:
        Directory in which to create the ``harmo_r_analysis`` symlink.
        Defaults to the user's home directory.

    Returns
    -------
    Path
        The created symlink path.
    """
    if target_dir is None:
        target_dir = str(Path.home())

    link_path = Path(target_dir) / "harmo_r_analysis"
    if link_path.exists():
        if link_path.is_symlink() and link_path.resolve() == SCRIPTS_DIR.resolve():
            logger.info("Symlink already exists: %s", link_path)
            return link_path
        logger.warning(
            "Path already exists but is not the expected symlink: %s",
            link_path,
        )
        return link_path

    link_path.symlink_to(SCRIPTS_DIR)
    logger.info("Created symlink: %s → %s", link_path, SCRIPTS_DIR)
    return link_path


def generate_rprofile_snippet(warehouse_path: Optional[str] = None) -> str:
    """Generate an ``.Rprofile`` snippet for Posit Workbench users.

    The snippet sets the warehouse path and sources the harmo R scripts,
    so that ``connectToIceberg()`` works out of the box.
    """
    wh = warehouse_path or get_warehouse_path()
    scripts = str(SCRIPTS_DIR)

    return f"""\
# ── harmo R bridge ─────────────────────────────────────────────
# Auto-generated by: python -m harmo.r_bridge.posit_helpers
Sys.setenv(HARMO_WAREHOUSE_PATH = "{wh}")

.harmo_scripts <- "{scripts}"
if (file.exists(file.path(.harmo_scripts, "iceberg_to_physio.R"))) {{
  message("[harmo] R analysis scripts available at: ", .harmo_scripts)
  message("[harmo] Warehouse path: ", Sys.getenv("HARMO_WAREHOUSE_PATH"))
  message("[harmo] Source scripts with:")
  message('  source(file.path(.harmo_scripts, "iceberg_to_physio.R"))')
  message('  source(file.path(.harmo_scripts, "analysis_visualization.R"))')
}}
# ── end harmo ──────────────────────────────────────────────────
"""
