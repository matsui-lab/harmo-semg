// Real-source E2E: no human confirmations are created or fabricated here.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const url=new URL(process.argv[2]), token=url.hash.slice(1);
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1056,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const headers={Authorization:'Bearer '+token,Origin:url.origin,'Content-Type':'application/json'};
    assert.equal((await page.request.get(url.origin+'/api/status')).status(),403);
    assert.equal((await page.request.get(url.origin+'/api/collection')).status(),403);
    assert.equal((await page.request.get(url.origin+'/api/library')).status(),403);
    assert.equal((await page.request.post(url.origin+'/api/register',{headers:{...headers,Origin:'https://example.org'},data:{}})).status(),403);
    assert.equal((await page.request.post(url.origin+'/api/evaluate',{headers:{...headers,Origin:'https://example.org'},data:{}})).status(),403);
    assert.equal((await page.request.get(url.origin+'/api/status',{headers:{Authorization:'Bearer invalid'}})).status(),403);
    assert.equal((await page.request.get(url.origin+'/api/artifact/unknown/decisions.json',{headers})).status(),404);
    await page.goto(url.href);
    assert.equal(await page.locator('#integration').isVisible(),false);
    await page.locator('#continueRun').click();
    assert.equal(await page.locator('#workspace').isVisible(),false);
    assert.equal(await page.locator('#evaluate').isEnabled(),true);
    assert.equal(await page.locator('#execute').isDisabled(),true);
    await page.locator('#evaluate').click();
    await page.waitForFunction(()=>!running,{timeout:180000});
    assert.equal(await page.evaluate(()=>activeRun?.phase),'evaluated',await page.locator('#runStatus').innerText());
    assert.equal(await page.evaluate(()=>activeRun.review_metrics.reviewed_items),0);
    assert.equal(await page.evaluate(()=>edits.decisions.every(d=>d.action==='unreviewed')),true);
    const plan=await page.evaluate(()=>activeRun);
    assert.equal(plan.ready_records,2);
    assert.equal(await page.locator('#execute').isEnabled(),true);
    await page.locator('#execute').click();
    await page.waitForFunction(()=>!running,{timeout:180000});
    assert.equal(await page.evaluate(()=>activeRun?.phase),'executed',await page.locator('#runStatus').innerText());
    const result=await page.evaluate(()=>activeRun);
    assert.equal(result.scientific_approval,false);
    assert.equal(result.amplitude_pooling_allowed,false);
    assert.equal(result.curves,16);
    assert.equal(result.comparisons,8);
    assert.equal(result.visual.shift_correction_applied,false);
    assert(result.work_items.every(w=>w.routing?.length));
    assert.equal(await page.locator('#nextActions h3').count(),5);
    await page.locator('#nextActions > summary').click();
    assert.match(await page.locator('#nextActions').innerText(),/must not be inherited by another signal/);
    await page.locator('#nextActions').screenshot({path:'/private/tmp/harmo-review-next-actions.png'});
    await page.locator('#nextActions > summary').click();
    assert.equal(await page.locator('#harmonizationVisual').isVisible(),true);
    assert.match(await page.locator('.mappingTable').innerText(),/Undefined/);
    assert.equal(await page.locator('#harmonizationVisual .resultPlot').count(),2);
    await page.locator('#harmonizationVisual').screenshot({path:'/private/tmp/harmo-result-before-after.png'});
    await page.locator('#view-compare').click();
    assert.match(await page.locator('.peakResult').innerText(),/Peak difference: held/);
    assert.equal(await page.locator('#harmonizationVisual .resultPlot').first().locator('path').count(),2);
    await page.locator('#harmonizationVisual').screenshot({path:'/private/tmp/harmo-result-comparison.png'});
    await page.locator('#integration').screenshot({path:'/private/tmp/harmo-integration-desktop.png'});
    const download=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download waveforms',exact:true}).click();
    await (await download).saveAs('/private/tmp/harmo-integration-test-curves.csv');
    await page.setViewportSize({width:392,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert((await page.locator('body').innerText()).length<4400);
    assert(!/[\u3040-\u30ff\u3400-\u9fff]/.test(await page.locator('body').innerText()));
    await page.locator('#registerResult').click();
    await page.waitForFunction(()=>!running,{timeout:180000});
    assert.equal(await page.locator('#registerResult').innerText(),'Saved',await page.locator('#registrationStatus').innerText());
    const registration=(await (await page.request.get(url.origin+'/api/status',{headers})).json()).result;
    assert.equal(registration.scientific_approval,false);
    const duplicate=await page.evaluate(async()=>{const request_id=crypto.randomUUID();await api('/api/register',{run_id:activeRun.run_id,request_id});let s;do{await new Promise(r=>setTimeout(r,100));s=await api('/api/status');}while(s.status==='running');return s;});
    assert.equal(duplicate.result.reused,true);
    assert.equal(duplicate.result.id,registration.id);
    await page.locator('#openCollection').click();
    await page.locator('#collectionList button').first().click();
    await page.waitForFunction(()=>document.querySelectorAll('#collectionDetail .resultPlot').length===2);
    assert.equal(await page.locator('#collectionDetail').getByText(/Unreviewed 70 items/).count(),1);
    assert.equal(await page.evaluate(()=>edits.decisions.every(d=>d.action==='unreviewed')),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.setViewportSize({width:1056,height:1000});
    await page.locator('#collectionPanel').screenshot({path:'/private/tmp/harmo-collection-desktop.png'});
    await page.locator('#showEntities').click();
    await page.locator('#libraryPurpose').waitFor({state:'visible'});
    assert.match(await page.locator('#entityPanel h3').innerText(),/Common records:.*2.*Derived signals:.*16/);
    assert.match(await page.locator('#purposeAssessments').innerText(),/Held 64 items/);
    const indexed=await page.evaluate(()=>api('/api/library'));
    assert.equal(indexed.common_records.length,2);
    assert.equal(indexed.derived_signals.length,16);
    assert.equal(indexed.use_assessments.length,128);
    assert(indexed.use_assessments.every(a=>a.assessment_scope==='source-contract-pair'&&!a.derived_signal_approval));
    await page.locator('#libraryPurpose').selectOption('waveform-shape');
    assert.match(await page.locator('#purposeAssessments').innerText(),/not been evaluated/);
    await page.locator('#libraryPurpose').selectOption('amplitude-pooling');
    assert.match(await page.locator('#purposeAssessments').innerText(),/Held 64 items/);
    await page.locator('#collectionPanel').screenshot({path:'/private/tmp/harmo-entity-library.png'});
    await page.setViewportSize({width:392,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.locator('#collectionPanel').getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#returnReview').click();
    assert.equal(await page.locator('#workspace').isVisible(),true);
    assert.equal(await page.locator('#integration').isVisible(),false);
    await page.reload();
    await page.locator('#openCollection').click();
    await page.locator('#collectionList button').first().click();
    await page.waitForFunction(()=>document.querySelectorAll('#collectionDetail .resultPlot').length===2);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed',run_id:result.run_id,output:result.output,curves:result.curves,comparisons:result.comparisons,reviewed_items:result.review_metrics.reviewed_items,purposes:result.purposes.map(p=>({purpose:p.purpose,evaluated:p.evaluated,statuses:p.statuses})),scientific_approval:result.scientific_approval},null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
